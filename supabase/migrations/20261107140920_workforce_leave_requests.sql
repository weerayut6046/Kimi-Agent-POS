CREATE TABLE "pos"."work_leave_quotas" (
	"branch_id" integer NOT NULL,
	"staff_id" integer NOT NULL,
	"year" integer NOT NULL,
	"type" text NOT NULL,
	"days" integer NOT NULL,
	CONSTRAINT "work_leave_quotas_branch_id_year_staff_id_type_pk" PRIMARY KEY("branch_id","year","staff_id","type"),
	CONSTRAINT "leave_quota_values_check" CHECK ("pos"."work_leave_quotas"."year" between 2000 and 2100 and "pos"."work_leave_quotas"."days" between 0 and 366 and
            "pos"."work_leave_quotas"."type" in ('sick', 'personal', 'vacation', 'other'))
);
ALTER TABLE "pos"."work_leave_quotas" ENABLE ROW LEVEL SECURITY;
CREATE TABLE "pos"."work_leave_requests" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "pos"."work_leave_requests_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"branch_id" integer NOT NULL,
	"staff_id" integer NOT NULL,
	"type" text NOT NULL,
	"start_on" date NOT NULL,
	"end_on" date NOT NULL,
	"note" text,
	"status" text DEFAULT 'pending' NOT NULL,
	"charged_days" integer,
	"reviewed_by" integer,
	"reviewer_name" text,
	"reviewed_at" timestamp with time zone,
	"review_note" text,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "leave_request_dates_check" CHECK ("pos"."work_leave_requests"."end_on" >= "pos"."work_leave_requests"."start_on" and extract(year from "pos"."work_leave_requests"."start_on") = extract(year from "pos"."work_leave_requests"."end_on")),
	CONSTRAINT "leave_request_days_check" CHECK (("pos"."work_leave_requests"."status" <> 'approved' or "pos"."work_leave_requests"."charged_days" is not null) and
            ("pos"."work_leave_requests"."charged_days" is null or "pos"."work_leave_requests"."charged_days" between 0 and ("pos"."work_leave_requests"."end_on" - "pos"."work_leave_requests"."start_on" + 1))),
	CONSTRAINT "leave_request_type_check" CHECK ("pos"."work_leave_requests"."type" in ('sick', 'personal', 'vacation', 'other')),
	CONSTRAINT "leave_request_status_check" CHECK ("pos"."work_leave_requests"."status" in ('pending', 'approved', 'rejected', 'cancelled'))
);
ALTER TABLE "pos"."work_leave_requests" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "pos"."work_leave_quotas" ADD CONSTRAINT "work_leave_quotas_branch_id_branches_id_fk" FOREIGN KEY ("branch_id") REFERENCES "pos"."branches"("id") ON DELETE restrict ON UPDATE no action;
ALTER TABLE "pos"."work_leave_quotas" ADD CONSTRAINT "work_leave_quotas_staff_id_staff_users_id_fk" FOREIGN KEY ("staff_id") REFERENCES "pos"."staff_users"("id") ON DELETE cascade ON UPDATE no action;
ALTER TABLE "pos"."work_leave_requests" ADD CONSTRAINT "work_leave_requests_branch_id_branches_id_fk" FOREIGN KEY ("branch_id") REFERENCES "pos"."branches"("id") ON DELETE restrict ON UPDATE no action;
ALTER TABLE "pos"."work_leave_requests" ADD CONSTRAINT "work_leave_requests_staff_id_staff_users_id_fk" FOREIGN KEY ("staff_id") REFERENCES "pos"."staff_users"("id") ON DELETE cascade ON UPDATE no action;
ALTER TABLE "pos"."work_leave_requests" ADD CONSTRAINT "work_leave_requests_reviewed_by_staff_users_id_fk" FOREIGN KEY ("reviewed_by") REFERENCES "pos"."staff_users"("id") ON DELETE set null ON UPDATE no action;
CREATE INDEX "leave_quota_staff_idx" ON "pos"."work_leave_quotas" USING btree ("staff_id");
CREATE INDEX "leave_request_staff_dates_idx" ON "pos"."work_leave_requests" USING btree ("staff_id","branch_id","start_on","end_on");
CREATE INDEX "leave_request_branch_dates_idx" ON "pos"."work_leave_requests" USING btree ("branch_id","start_on");
CREATE INDEX "leave_request_reviewer_idx" ON "pos"."work_leave_requests" USING btree ("reviewed_by");
REVOKE ALL ON TABLE "pos"."work_leave_requests", "pos"."work_leave_quotas" FROM PUBLIC, anon, authenticated;
